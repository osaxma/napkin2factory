"""Build the napkin2factory logo package from parameters.

Everything in ``brand/svg`` and ``brand/png`` is generated by this file; edit the
parameters below and re-run instead of editing the outputs by hand.

    python3 brand/build.py            # SVGs, plus PNGs/ICO when rsvg-convert/magick exist
    python3 brand/build.py --no-png   # SVGs only

Standard library only. The drawing is a 2:1 isometric projection on a 100 x 100 canvas:
a point (a, b, z) on the napkin plane (z up) lands at x = CX + a - b, y = CY + (a + b)/2 - z.
"""

from __future__ import annotations

import argparse
import math
import random
import re
import shutil
import subprocess
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path

HERE = Path(__file__).resolve().parent

# --- palette ---------------------------------------------------------------------------
TILE = "#1C1B1A"
NAPKIN = "#FBF8F1"
CREASE = "#DED3BF"
DOTS = "#D9CDB6"
FOLD = "#E6DCC8"
FOLD_EDGE = "#D6C9B1"
PEN = "#2346B0"
PART_TOP = "#F3A27C"
PART_SIDE_A = "#E8692E"
PART_SIDE_B = "#C9541F"
CUT_WALL = "#B4471A"
TEXT_ON_DARK = "#F4F1EC"
TEXT_ON_LIGHT = "#1C1B1A"


@dataclass
class Variant:
    """Parameters for one size variant of the icon."""

    name: str
    scale: float = 0.86  # overall size of napkin + part inside the tile
    gap: float = 36.0  # napkin-to-part distance (canvas units)
    thickness: float = 3.2  # plate thickness
    tile_radius: float = 22.0
    dots: bool = True  # pressed-dot border on the napkin
    fold: bool = True  # folded corner on the napkin
    creases: bool = True
    hand_sketch: bool = True  # pen-sketched hexagon + handwritten n2f (else a plain outline)
    outline_width: float = 1.25
    word_width: float = 1.0
    cut_letters: bool = True
    path_vertices: list[int] = field(default_factory=lambda: [2, 1, 5])
    path_width: float = 0.9
    path_dash: str = "2 2"
    path_opacity: float = 0.75
    sketch_seed: int = 4
    word_seed: int = 21


MASTER = Variant("icon")
SMALL_32 = Variant(
    "icon-32", scale=0.95, gap=39.6, thickness=4, dots=False, hand_sketch=False,
    outline_width=3, cut_letters=False, path_vertices=[2, 5], path_width=2.2,
    path_dash="3.5 3", path_opacity=0.9,
)
SMALL_16 = Variant(
    "icon-16", scale=1.08, gap=22, thickness=6, tile_radius=16, dots=False, fold=False,
    creases=False, hand_sketch=False, outline_width=5, cut_letters=False, path_vertices=[],
)

# --- geometry --------------------------------------------------------------------------
Pt = tuple[float, float, float]
CX = 50.0


class Proj:
    """Isometric projection with an adjustable vertical centre."""

    def __init__(self, cy: float = 50.0) -> None:
        """Create a projection centred at (CX, cy)."""
        self.cy = cy

    def __call__(self, p: Pt) -> tuple[float, float]:
        """Project a 3D point to canvas coordinates."""
        a, b, z = p
        return (CX + a - b, self.cy + 0.5 * a + 0.5 * b - z)

    def pts(self, ps: list[Pt]) -> str:
        """Format projected points for an SVG ``points`` attribute."""
        return " ".join(f"{x:.2f},{y:.2f}" for x, y in map(self, ps))


def add(u: Pt, v: Pt) -> Pt:
    """Add two vectors."""
    return (u[0] + v[0], u[1] + v[1], u[2] + v[2])


def sub(u: Pt, v: Pt) -> Pt:
    """Subtract two vectors."""
    return (u[0] - v[0], u[1] - v[1], u[2] - v[2])


def cross(u: Pt, v: Pt) -> Pt:
    """Cross product."""
    return (u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0])


def dot(u: Pt, v: Pt) -> float:
    """Dot product."""
    return u[0] * v[0] + u[1] * v[1] + u[2] * v[2]


VIEW: Pt = (1.0, 1.0, 1.0)  # direction towards the viewer


def hexagon(r: float) -> list[Pt]:
    """Hexagon with vertex 0 at the front-right; 1 front-left, 2 left, 5 right."""
    return [
        (r * math.cos(math.pi / 6 + i * math.pi / 3), r * math.sin(math.pi / 6 + i * math.pi / 3), 0)
        for i in range(6)
    ]


def arc(cx: float, cy: float, r: float, a0: float, a1: float, n: int = 10) -> list[tuple[float, float]]:
    """Points along a circular arc, angles in degrees."""
    return [
        (cx + r * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
         cy + r * math.sin(math.radians(a0 + (a1 - a0) * i / n)))
        for i in range(n + 1)
    ]


# Cut-out letters: n, 2, f on a 26.8 x 10 grid (stroke 2.6).
_T = 2.6
_GLYPH_N = [(0.0, 0.0)] + arc(4, 6, 4, 180, 0) + [(8.0, 0.0), (8 - _T, 0.0)] + arc(4, 6, 4 - _T, 0, 180) + [(_T, 0.0)]
_GLYPH_2 = (
    [(0.0, 0.0), (8.0, 0.0), (8.0, _T), (3.9, _T)]
    + arc(4.4, 6.8, 3.2, -40, 180, 12)
    + arc(4.4, 6.8, 3.2 - _T * 0.85, 180, -40, 12)
    + [(0.0, _T * 0.9)]
)
_GLYPH_F = (
    [(1.4, 0.0), (4.0, 0.0), (4.0, 4.2), (6.6, 4.2), (6.6, 6.6), (4.0, 6.6), (4.0, 7.6),
     (7.6, 7.6), (7.6, 10.0), (4.0, 10.0)]
    + arc(4, 7.6, 2.6, 90, 180, 6)[1:]
    + [(1.4, 6.6), (0.0, 6.6), (0.0, 4.2), (1.4, 4.2)]
)
GLYPHS = [_GLYPH_N, [(x + 9.6, y) for x, y in _GLYPH_2], [(x + 19.2, y) for x, y in _GLYPH_F]]
GLYPH_W, GLYPH_H = 26.8, 10.0

# Handwritten n2f: pen strokes as point lists on a 21 x 9.6 grid.
HAND_STROKES = [
    [(1, 7.2), (1, 0), (1, 3.2), (2.2, 6), (3.8, 7), (5.3, 6.3), (6, 4.8), (6, 0)],
    [(8.3, 5.6), (9.3, 7.1), (11, 7.6), (12.8, 7), (13.4, 5.6), (12.6, 3.8), (10.4, 1.8), (8.2, 0),
     (11, 0.15), (14, 0)],
    [(20.4, 8.8), (19.4, 9.7), (18, 9.6), (17.2, 8.5), (17, 6.4), (17, 0)],
    [(15.3, 5.6), (19.4, 5.8)],
]
HAND_W, HAND_H = 21.0, 9.6


def flat(g: list[tuple[float, float]], k: float, w: float, h: float) -> list[Pt]:
    """Lay a 2D glyph flat on the napkin plane, reading along +a, centred."""
    return [((x - w / 2) * k, -(y - h / 2) * k, 0.0) for x, y in g]


# --- drawing helpers -------------------------------------------------------------------
def catmull(points: list[tuple[float, float]], closed: bool) -> str:
    """Smooth path through points (Catmull-Rom as cubic Béziers)."""
    n = len(points)

    def get(i: int) -> tuple[float, float]:
        return points[i % n]

    d = f"M{points[0][0]:.2f} {points[0][1]:.2f}"
    for i in range(n if closed else n - 1):
        p0, p1, p2, p3 = get(i - 1), get(i), get(i + 1), get(i + 2)
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d += f" C{c1[0]:.2f} {c1[1]:.2f} {c2[0]:.2f} {c2[1]:.2f} {p2[0]:.2f} {p2[1]:.2f}"
    return d


def pen_polygon(pr: Proj, poly: list[Pt], seed: int, width: float) -> list[str]:
    """Hand-drawn polygon: one slightly bowed stroke per edge, overshooting the corners."""
    r = random.Random(seed)
    out = []
    for i, p in enumerate(poly):
        q = poly[(i + 1) % len(poly)]
        dx, dy = q[0] - p[0], q[1] - p[1]
        ln = math.hypot(dx, dy)
        ux, uy = dx / ln, dy / ln
        o1, o2 = r.uniform(0.3, 1.3), r.uniform(0.3, 1.3)
        a = (p[0] - ux * o1 + r.uniform(-0.3, 0.3), p[1] - uy * o1 + r.uniform(-0.3, 0.3), 0.0)
        b = (q[0] + ux * o2 + r.uniform(-0.3, 0.3), q[1] + uy * o2 + r.uniform(-0.3, 0.3), 0.0)
        bow = r.uniform(-0.9, 0.9)
        m = ((a[0] + b[0]) / 2 - uy * bow, (a[1] + b[1]) / 2 + ux * bow, 0.0)
        (ax, ay), (mx, my), (bx, by) = pr(a), pr(m), pr(b)
        cx, cy = 2 * mx - (ax + bx) / 2, 2 * my - (ay + by) / 2
        out.append(
            f'<path d="M{ax:.2f} {ay:.2f} Q{cx:.2f} {cy:.2f} {bx:.2f} {by:.2f}" pathLength="1" '
            f'fill="none" stroke="{PEN}" stroke-width="{width}" stroke-linecap="round"/>'
        )
    return out


def handwriting(pr: Proj, k: float, seed: int, width: float) -> list[str]:
    """Handwritten n2f, one path per pen stroke."""
    r = random.Random(seed)
    out = []
    for stroke in HAND_STROKES:
        pts3 = [((x - HAND_W / 2) * k + r.uniform(-0.2, 0.2), -(y - HAND_H / 2) * k + r.uniform(-0.2, 0.2), 0.0)
                for x, y in stroke]
        out.append(
            f'<path d="{catmull([pr(p) for p in pts3], False)}" pathLength="1" fill="none" '
            f'stroke="{PEN}" stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round"/>'
        )
    return out


def prism_faces(pr: Proj, base: list[Pt], e: Pt) -> list[str]:
    """Visible faces of a prism (base polygon extruded by e), back to front."""
    area: Pt = (0.0, 0.0, 0.0)
    for i in range(len(base)):
        area = add(area, cross(base[i], base[(i + 1) % len(base)]))
    if dot(area, e) < 0:
        base = base[::-1]
    faces = []
    for i in range(len(base)):
        p, q = base[i], base[(i + 1) % len(base)]
        n = cross(sub(q, p), e)
        if dot(n, VIEW) <= 1e-9:
            continue
        quad = [p, q, add(q, e), add(p, e)]
        centre = tuple(sum(v[j] for v in quad) / 4 for j in range(3))
        ln = math.hypot(*n)
        col = PART_SIDE_A if abs(n[0] / ln) >= abs(n[1] / ln) else PART_SIDE_B
        faces.append((dot(centre, VIEW), quad, col))  # type: ignore[arg-type]
    out = [
        f'<polygon points="{pr.pts(q)}" fill="{c}" stroke="{c}" stroke-width=".4" stroke-linejoin="round"/>'
        for _, q, c in sorted(faces, key=lambda f: f[0])
    ]
    top = [add(p, e) for p in base]
    out.append(
        f'<polygon id="part-top" points="{pr.pts(top)}" fill="{PART_TOP}" stroke="{PART_TOP}" '
        f'stroke-width=".4" stroke-linejoin="round"/>'
    )
    return out


# --- the icon --------------------------------------------------------------------------
def icon_body(v: Variant, prefix: str = "") -> str:
    """SVG content (no outer <svg>) of one icon variant, as named, animatable layers."""
    s, rad, h = 22 * v.scale, 16 * v.scale, v.thickness
    hexa = hexagon(rad)
    # Centre the group (napkin tip to plate top) vertically.
    pr = Proj(50.0)
    ys = [pr((-s, -s, 0))[1], pr((s, s, 0))[1]] + [pr(add(p, (0, 0, v.gap + h)))[1] for p in hexa]
    pr = Proj(50.0 + (50.0 - (min(ys) + max(ys) + 2) / 2))

    out = [f'<g id="{prefix}tile"><rect width="100" height="100" rx="{v.tile_radius}" fill="{TILE}"/></g>']

    # napkin
    f = s * 0.42
    sheet = [(-s, -s, 0), (s - f, -s, 0), (s, -s + f, 0), (s, s, 0), (-s, s, 0)] if v.fold else \
        [(-s, -s, 0), (s, -s, 0), (s, s, 0), (-s, s, 0)]
    nap = [f'<polygon id="{prefix}napkin-sheet" points="{pr.pts(sheet)}" fill="{NAPKIN}"/>']
    if v.creases:
        nap.append(
            f'<g id="{prefix}napkin-creases" stroke="{CREASE}" stroke-width="1.3">'
            f'<polyline points="{pr.pts([(0, -s, 0), (0, s, 0)])}"/>'
            f'<polyline points="{pr.pts([(-s, 0, 0), (s, 0, 0)])}"/></g>'
        )
    if v.dots:
        t = s - 3.2
        ring = [(-t, -t, 0), (t - f + 1.5, -t, 0), (t, -t + f - 1.5, 0), (t, t, 0), (-t, t, 0)] if v.fold \
            else [(-t, -t, 0), (t, -t, 0), (t, t, 0), (-t, t, 0)]
        nap.append(
            f'<polygon id="{prefix}napkin-dots" points="{pr.pts(ring)}" fill="none" stroke="{DOTS}" '
            f'stroke-width="1.5" stroke-dasharray=".1 3.2" stroke-linecap="round"/>'
        )
    if v.fold:
        flap = [(s - f, -s, 0), (s, -s + f, 0), (s - f, -s + f, 0)]
        nap.append(
            f'<polygon id="{prefix}napkin-fold" points="{pr.pts(flap)}" '
            f'fill="{FOLD}" stroke="{FOLD_EDGE}" stroke-width=".6" stroke-linejoin="round"/>'
        )
    out.append(f'<g id="{prefix}napkin">{"".join(nap)}</g>')

    # sketch
    if v.hand_sketch:
        outline = pen_polygon(pr, hexa, v.sketch_seed, v.outline_width)
        word = handwriting(pr, 0.95 * v.scale * 0.92, v.word_seed, v.word_width)
        out.append(
            f'<g id="{prefix}sketch"><g id="{prefix}sketch-outline">{"".join(outline)}</g>'
            f'<g id="{prefix}sketch-word">{"".join(word)}</g></g>'
        )
    else:
        out.append(
            f'<g id="{prefix}sketch"><polygon id="{prefix}sketch-outline" points="{pr.pts(hexa)}" fill="none" '
            f'stroke="{PEN}" stroke-width="{v.outline_width}" stroke-linejoin="round" pathLength="1"/></g>'
        )

    # projection lines (napkin -> part)
    lines = []
    for n, i in enumerate(v.path_vertices, 1):
        (x1, y1), (x2, y2) = pr(hexa[i]), pr(add(hexa[i], (0, 0, v.gap)))
        lines.append(
            f'<line id="{prefix}projection-{n}" x1="{x1:.2f}" y1="{y1:.2f}" x2="{x2:.2f}" y2="{y2:.2f}" '
            f'stroke="{PEN}" stroke-width="{v.path_width}" stroke-dasharray="{v.path_dash}" '
            f'stroke-linecap="round" opacity="{v.path_opacity}"/>'
        )
    out.append(f'<g id="{prefix}projection">{"".join(lines)}</g>')

    # part
    base = [add(p, (0, 0, v.gap)) for p in hexa]
    part = prism_faces(pr, base, (0, 0, h))
    part[-1] = part[-1].replace('id="part-top"', f'id="{prefix}part-top"')
    if v.cut_letters:
        cut = []
        for n, g in enumerate(GLYPHS):
            top = [add(p, (0, 0, v.gap + h)) for p in flat(g, 0.78 * v.scale, GLYPH_W, GLYPH_H)]
            floor = [add(p, (0, 0, -1.0)) for p in top]
            cid = f"{prefix}cut-clip-{n}"
            cut.append(
                f'<clipPath id="{cid}"><polygon points="{pr.pts(top)}"/></clipPath>'
                f'<g id="{prefix}cut-{"n2f"[n]}"><polygon points="{pr.pts(top)}" fill="{CUT_WALL}"/>'
                f'<polygon points="{pr.pts(floor)}" fill="{TILE}" clip-path="url(#{cid})"/></g>'
            )
        part.append(f'<g id="{prefix}part-cut">{"".join(cut)}</g>')
    out.append(f'<g id="{prefix}part" data-gap="{v.gap}">{"".join(part)}</g>')
    return "\n".join(out)


def svg_doc(body: str, w: float, h: float, title: str, extra_head: str = "") -> str:
    """Wrap content in a standalone SVG document."""
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w * 5:g}" height="{h * 5:g}" '
        f'role="img" aria-label="{title}">\n<title>{title}</title>\n{extra_head}{body}\n</svg>\n'
    )


ANIMATION_CSS = """<style>
  #sketch path, #sketch polygon { stroke-dasharray: 1; animation: n2f-draw .45s ease-out both; }
  #projection line { transform-box: fill-box; transform-origin: 50% 100%; animation: n2f-grow .5s ease-out both; }
  #part { animation: n2f-rise .7s cubic-bezier(.2,.8,.2,1) both; animation-delay: 2.1s; }
  @keyframes n2f-draw { from { stroke-dashoffset: 1; } to { stroke-dashoffset: 0; } }
  @keyframes n2f-grow { from { transform: scaleY(0); } to { transform: scaleY(1); } }
  @keyframes n2f-rise { from { transform: translateY(var(--gap)); opacity: 0; } to { transform: none; opacity: 1; } }
  @media (prefers-reduced-motion: reduce) { * { animation: none !important; } }
</style>
"""


def animated_icon() -> str:
    """Master icon with a CSS intro: pen draws the sketch, lines rise, the part lifts off."""
    body = icon_body(MASTER)
    clock = [0.2]

    def stagger(step: float) -> Callable[[re.Match[str]], str]:
        def repl(m: re.Match[str]) -> str:
            delay = clock[0]
            clock[0] += step
            return f'{m.group(0)}style="animation-delay:{delay:.2f}s" '
        return repl

    body = re.sub(r"<path (?=d=)", stagger(0.12), body)  # pen strokes, in drawing order
    clock[0] += 0.1
    body = re.sub(r"<line ", stagger(0.15), body)  # projection lines
    body = body.replace('<g id="part"', f'<g id="part" style="--gap:{MASTER.gap}px"')
    return svg_doc(body, 100, 100, "napkin2factory", ANIMATION_CSS)


def lockup(text_fill: str, prefix: str) -> str:
    """Icon plus wordmark, horizontal."""
    inner = icon_body(MASTER, prefix)
    return svg_doc(
        f'<svg x="10" y="10" width="100" height="100" viewBox="0 0 100 100">{inner}</svg>'
        f'<text id="{prefix}wordmark" x="132" y="76" font-family="Inter, \'Helvetica Neue\', Helvetica, Arial, '
        f'sans-serif" font-size="46" font-weight="600" letter-spacing="-.5" fill="{text_fill}">napkin2factory</text>',
        520, 120, "napkin2factory",
    )


# --- outputs ---------------------------------------------------------------------------
def build(out: Path, png: bool) -> None:
    """Write every SVG, and PNG/ICO exports when the tools are available."""
    svg_dir, png_dir = out / "svg", out / "png"
    svg_dir.mkdir(parents=True, exist_ok=True)
    files = {
        "n2f-icon.svg": svg_doc(icon_body(MASTER), 100, 100, "napkin2factory"),
        "n2f-icon-32.svg": svg_doc(icon_body(SMALL_32), 100, 100, "napkin2factory"),
        "n2f-icon-16.svg": svg_doc(icon_body(SMALL_16), 100, 100, "napkin2factory"),
        "n2f-mark.svg": svg_doc(icon_body(MASTER).split("\n", 1)[1], 100, 100, "napkin2factory"),
        "n2f-icon-animated.svg": animated_icon(),
        "n2f-lockup-on-dark.svg": lockup(TEXT_ON_DARK, "d-"),
        "n2f-lockup-on-light.svg": lockup(TEXT_ON_LIGHT, "l-"),
    }
    for name, text in files.items():
        (svg_dir / name).write_text(text)
    print(f"wrote {len(files)} SVGs to {svg_dir}")

    rsvg = shutil.which("rsvg-convert")
    if not png or not rsvg:
        if png:
            print("rsvg-convert not found: skipped PNGs")
        return
    png_dir.mkdir(exist_ok=True)

    def render(src: str, dst: str, width: int) -> None:
        subprocess.run([rsvg, "-w", str(width), str(svg_dir / src), "-o", str(png_dir / dst)], check=True)

    for size in (1024, 512, 256, 192, 180, 128, 64):
        render("n2f-icon.svg", f"n2f-icon-{size}.png", size)
    render("n2f-icon-32.svg", "n2f-icon-48.png", 48)
    render("n2f-icon-32.svg", "n2f-icon-32.png", 32)
    render("n2f-icon-16.svg", "n2f-icon-16.png", 16)
    render("n2f-mark.svg", "n2f-mark-1024.png", 1024)
    render("n2f-lockup-on-dark.svg", "n2f-lockup-on-dark.png", 1560)
    render("n2f-lockup-on-light.svg", "n2f-lockup-on-light.png", 1560)
    magick = shutil.which("magick")
    if magick:
        subprocess.run([magick, *(str(png_dir / f"n2f-icon-{n}.png") for n in (16, 32, 48)),
                        str(png_dir / "favicon.ico")], check=True)
    print(f"wrote PNGs to {png_dir}")


def main() -> None:
    """Command-line entry point."""
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=HERE)
    ap.add_argument("--no-png", action="store_true", help="only write SVGs")
    args = ap.parse_args()
    build(args.out, not args.no_png)


if __name__ == "__main__":
    main()
